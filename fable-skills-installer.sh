# Fable級 抜け漏れ検査

コード変更を「完了」と報告する前に必ず実行する。
Fable が自発的にやる波及先チェックを、機械的な手順として強制するのが目的。

## 実行原則

- 各項目は **Grep/Glob で実際に列挙して** 確認する。記憶や「たぶん」で済ませない。
- 検査対象は「今回の変更に関係する範囲」に絞る（無関係な全ファイル読みはしない）。
- 見つけた問題は、依頼範囲内なら修正、範囲外なら報告に留める（勝手に直さない）。

## チェックリスト

### A. 参照の完全性（リネーム・シグネチャ変更時は必須）

1. 変更・削除・リネームした識別子（関数名/変数名/型名/ファイル名）ごとに、
   **旧名称を Grep** する。ヒット0件になるまで完了と言わない。
   - 検索対象にコード以外も含める: 文字列リテラル、コメント、md、json、スクリプト
2. シグネチャ（引数の数・型・戻り値）を変えた関数は、**全呼び出し元を Grep で列挙**し、
   1件ずつ新シグネチャに適合しているか確認する。

### B. データ契約

3. 型・interface・JSON構造を変えた場合、その構造を生成する側と消費する側の両方を確認。
4. プロジェクトの設定ファイル（settings.json 等）に定義済みの定数・パスを
   ハードコードで複製していないか。数値の大小関係・順序に不変条件があるデータ
   （例: 開始 <= 終了、時系列の昇順）は、その不変条件が保たれているか。

### C. エッジケースとエラーパス

5. 追加・変更したロジックについて: 空配列/0件/null/undefined/境界値（最初と最後の要素）で壊れないか。
6. 失敗しうる処理（ファイルIO、外部コマンド、パース）に失敗時の挙動があるか。
   ただし周囲のコードが握り潰しスタイルなら過剰な防御を足さない（流儀に合わせる）。

### D. 一貫性・ドキュメント矛盾

7. 変更で嘘になったものはないか: README、コメント、settings.json の説明、
   コマンド定義（.claude/commands/）、スキル内の記述。
8. 同じ知識の重複箇所（定数・パターン・ルール）が他所にもあるなら、片方だけ直していないか。

### E. 未完了の痕跡

9. 自分が入れた TODO / 仮実装 / デバッグ出力 / コメントアウトの残骸が残っていないか
   （`git diff` を最後に一度見る）。
10. 追加したファイル・削除したファイルが import/参照と整合しているか。

## 完了報告の形式

検査後、報告の末尾に1行で結果を書く:

- 問題なし → `抜け漏れ検査: A〜E 実施、問題なし`
- 発見・修正 → `抜け漏れ検査: B4でフレーム矛盾を検出し修正済み`
- 範囲外の発見 → 修正せず「発見事項」として報告

「検査した」と書けるのは実際に Grep/diff を実行した場合のみ。
