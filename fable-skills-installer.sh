# Fable と Opus 4.8 の根本的な違い（分析）

このドキュメントは fable-core / fable-check / fable-refactor スキルの設計根拠。
通常のタスクでは読み込まない（トークン節約）。ユーザーに差分を説明する時だけ参照する。

## モデルの位置づけ

- **Claude Fable 5**: Claude 5 ファミリー第1弾。Opus より上位の「Mythos級」ティア。
  Claude Mythos 5 と同一の基盤モデル（Fable は安全対策を追加した一般提供版）。
- **Claude Opus 4.8**: Claude 4 世代の最上位。十分に高性能だが、以下の点で Fable に劣る。

## 品質差が出る5つの領域と、スキルでの補完方法

### 1. 抜け漏れ検出力（最大の差）

**Fable の挙動**: 変更点そのものではなく「変更が波及する先」を自発的に全列挙する。
呼び出し元、データ契約の依存箇所、ドキュメントとの矛盾、リネーム漏れ、
エラーパスの未処理、off-by-one を、指示されなくても網羅的に洗う。

**Opus の傾向**: 変更したファイルの中では正確だが、波及先の列挙が指示依存。
「聞かれたことには正しく答えるが、聞かれていない欠陥を見つける率」が下がる。

**補完**: fable-check の機械的チェックリスト。自発性の差を「手順の強制」で埋める。
チェックリストは Grep での実列挙を要求する（記憶ベースの「たぶん大丈夫」を禁止）。

### 2. 自己検証・キャリブレーション

**Fable の挙動**: 結論を出す前に自分で反証を試みる。未検証のものを検証済みと言わない。
テスト失敗や部分的な完成を装飾せずそのまま報告する。

**Opus の傾向**: 最初にもっともらしい仮説に到達すると、それを支持する証拠を集めがち。
「動くはず」の報告が混ざる。

**補完**: fable-core 原則2。「反証を1つ実行してから報告」を義務化。

### 3. 人間的な判断力（何が重要かの選別）

**Fable の挙動**: 読み手の次の行動を変える情報を先頭に置き、変えない詳細を捨てる。
字面ではなく目的に応える（問題の描写には診断を、依頼には実装を返す）。

**Opus の傾向**: 網羅的だが平坦。全部を同じ重みで報告し、読み手に選別を委ねる。

**補完**: fable-core 原則1・5。結論ファーストと重要度順を形式として強制。

### 4. スコープの節度

**Fable の挙動**: 頼まれた範囲を正確に守り、範囲外の発見は「報告」に留める。
過剰な抽象化やリファクタの混入をしない。

**Opus の傾向**: 善意の範囲拡大（ついでの改善・過剰な防御コード）が混ざりやすい。

**補完**: fable-core 原則4。fable-refactor の「挙動を変えない」制約。

### 5. トークン効率

これはモデル差ではなく運用の問題。Fable は高価なので、
「常時読込を最小化し、詳細ルールを必要時ロードするスキル構成」と
「機械的作業の haiku 委譲」で、どちらのモデルでも消費を抑える。

## 埋められない差

以下は手順化では完全に埋まらない。ここに該当する作業だけ Fable を使う判断基準になる:

- 大規模で構造が不明瞭なコードベースの一発読解
- 仕様の矛盾を「読んだ瞬間に」察知する感度（チェックリスト外の未知の欠陥クラス）
- 長大なコンテキストでの一貫性維持

逆に言えば、定型ワークフロー（このリポジトリの動画制作タスク等）や
チェックリスト化可能な検査は Opus 4.8 + 本スキル群でほぼ同等の結果になる。
