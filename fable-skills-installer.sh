# Fable級 リファクタリング手順

前提: `fable-core`（思考原則）を先に読んでいること。
鉄則: **リファクタリングは挙動を変えない。** 挙動変更が必要だと分かったら、
勝手に混ぜずユーザーに報告して切り分ける。

## 手順

### 1. 現状把握（書き換える前に読む）

- 対象コードの呼び出し元・参照元を Grep で全列挙し、件数を把握する。
- 既存のテスト・型チェック・lint の有無を確認（`package.json` の scripts を見る）。
  あれば着手前に一度実行し、**着手前から壊れているもの**を記録する
  （自分の変更のせいにしない／自分のせいでないことの証明になる）。

### 2. 計画（小さく刻む）

- 変更を「各ステップ後もビルドが通る」単位に分割する。
- 大きなリネームや移動は1ステップ1種類。複数種類の変更を1コミットに混ぜない。
- 判断基準:
  - **重複の統合**: 3回以上繰り返されるパターンのみ対象。2回は許容（早すぎる抽象化を避ける）。
  - **抽象化の追加**: 呼び出し側のコードが明確に単純になる場合のみ。層を増やすだけなら却下。
  - **命名**: 周囲の既存の命名規則に従う。独自スタイルを持ち込まない。

### 3. 実行

- 1ステップごとに型チェック/テストを回す（ある場合）。
- 機械的な一括置換（同一パターンの多数ファイル修正）は haiku サブエージェントに
  委譲してトークンを節約する。判断が要る箇所は自分でやる。

### 4. 完了検査

- `fable-check` スキルのチェックリストを必ず実行（特に A: 旧名称の Grep ゼロ確認）。
- `git diff` を通読し、意図しない変更・デバッグ残骸がないか確認する。
- 着手前に通っていたテスト/チェックが全て通ることを確認する。

## 報告形式

1. 何をどう変えたか（構造の before → after を1〜3文で）
2. 挙動が変わらないことの根拠(テスト結果 / 型チェック / 呼び出し元の全数確認)
3. 抜け漏れ検査の結果1行
4. やらなかったこと・見つけたが範囲外だったこと(あれば)
